CREATE DATABASE TIENDA;
USE TIENDA;

CREATE TABLE CLIENTES (
cod_cliente INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
nombre VARCHAR(50) NOT NULL,
email VARCHAR(100) UNIQUE
);

CREATE TABLE ARTICULOS (
cod_articulo INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
descripcion VARCHAR(100) NOT NULL,
precio_venta DECIMAL(8,2) NOT NULL CHECK (precio_venta > 0),
stock INT UNSIGNED DEFAULT 0
);

CREATE TABLE PEDIDOS (
cod_pedido INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
cod_cliente INT UNSIGNED NOT NULL,
cod_articulo INT UNSIGNED NOT NULL,
cantidad INT UNSIGNED NOT NULL,
fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
FOREIGN KEY (cod_cliente) REFERENCES CLIENTES (cod_cliente),
FOREIGN KEY (cod_articulo) REFERENCES ARTICULOS (cod_articulo)
);